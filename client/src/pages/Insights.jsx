import { useState } from 'react';
import { ChevronDown, ChevronUp, Lightbulb } from 'lucide-react';
import { INSIGHT_THEMES } from '../data/demo';
import { PriorityDot, Badge } from '../components/ui';

// ── Theme card ────────────────────────────────────────────────────
function ThemeCard({ theme }) {
  const [expanded, setExpanded] = useState(false);

  return (
    <div className="theme-card">
      <div className="theme-card-header">
        <div style={{ flex: 1 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 2 }}>
            <PriorityDot level={theme.priority} />
            <div className="theme-title">{theme.title}</div>
          </div>
          <div className="theme-count">{theme.count} supporting signals</div>
        </div>
        <Badge variant={theme.priority === 'high' ? 'danger' : 'warning'}>
          {theme.priority}
        </Badge>
      </div>

      {/* Frequency bar */}
      <div className="theme-bar-track">
        <div className="theme-bar-fill" style={{ width: `${theme.percent}%` }} />
      </div>
      <div style={{ fontSize: 11.5, color: 'var(--color-text-tertiary)', marginBottom: 12 }}>
        {theme.percent}% of total signals this month
      </div>

      {/* AI summary */}
      <p style={{ fontSize: 13, color: 'var(--color-text-secondary)', lineHeight: 1.6, marginBottom: 12 }}>
        {theme.summary}
      </p>

      {/* Quotes toggle */}
      <button
        id={`theme-quotes-${theme.id}`}
        className="btn btn-ghost btn-sm"
        onClick={() => setExpanded((x) => !x)}
        style={{ padding: '4px 0', color: 'var(--color-accent)' }}
      >
        {expanded ? <ChevronUp size={13} /> : <ChevronDown size={13} />}
        {expanded ? 'Hide quotes' : `Show ${theme.quotes.length} supporting quotes`}
      </button>

      {expanded && (
        <div className="quote-list" style={{ marginTop: 12 }}>
          {theme.quotes.map((q, i) => (
            <div key={i} className="quote-item">
              "{q.text}"
              <div className="quote-source">— {q.source}</div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}

// ── Page ──────────────────────────────────────────────────────────
export default function Insights() {
  return (
    <div className="page-content">
      {/* Info banner */}
      <div
        style={{
          background: 'var(--color-bg)',
          border: '1px solid var(--color-border)',
          borderRadius: 'var(--radius-lg)',
          padding: '14px 18px',
          display: 'flex',
          gap: 12,
          alignItems: 'flex-start',
          marginBottom: 24,
          boxShadow: 'var(--shadow-sm)',
        }}
      >
        <Lightbulb size={16} style={{ color: 'var(--color-accent)', marginTop: 2, flexShrink: 0 }} />
        <div>
          <div style={{ fontSize: 13.5, fontWeight: 600, color: 'var(--color-text)', marginBottom: 3 }}>
            AI Insights — Demo Mode
          </div>
          <div style={{ fontSize: 13, color: 'var(--color-text-secondary)', lineHeight: 1.55 }}>
            In production, themes are generated by clustering your feedback through an LLM pipeline.
            Below is representative output based on the demo dataset. No live AI calls are made.
          </div>
        </div>
      </div>

      {/* Theme grid */}
      <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 16 }}>
        {INSIGHT_THEMES.map((theme) => (
          <ThemeCard key={theme.id} theme={theme} />
        ))}
      </div>
    </div>
  );
}
